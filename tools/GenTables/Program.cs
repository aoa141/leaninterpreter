static IEnumerable<(string Ext, Obj[] Entries)> Entries(Obj moduleData) =>
    Arr(lean_ctor_get(moduleData, 4)).Select(e => (Name(lean_ctor_get(e, 0)), Arr(lean_ctor_get(e, 1))));

static Obj[] Arr(Obj a) => ((ArrayObj)a).m_data.Take((int)((ArrayObj)a).m_size).ToArray();

static string Name(Obj n)
{
    if (lean_is_scalar(n)) return "";
    var p = Name(lean_ctor_get(n, 0));
    var f = lean_ctor_get(n, 1);
    var c = lean_obj_tag(n) == 1 ? lean_string_to_net(f) : lean_unbox(f).ToString();
    return p.Length == 0 ? c : p + "." + c;
}

// `ExternAttrData` is a trivial structure: its `entries : List ExternEntry`
static string ExternSymbol(Obj l)
{
    for (; !lean_is_scalar(l); l = lean_ctor_get(l, 1))
    {
        var e = lean_ctor_get(l, 0);
        if (lean_is_scalar(e) || lean_obj_tag(e) != 2) continue; // standard (backend, fn)
        var backend = Name(lean_ctor_get(e, 0));
        if (backend is "c" or "all") return lean_string_to_net(lean_ctor_get(e, 1));
    }
    return null;
}

static string Ty(Obj t) => lean_is_scalar(t)
    ? new[] { "f64", "u8", "u16", "u32", "u64", "usize", "irr", "obj", "tobj", "f32", "struct", "union", "tagged", "void" }[lean_unbox(t)]
    : "struct";

static string Cs(string t) => t switch
{
    "obj" or "tobj" or "tagged" or "irr" => "Obj", "u8" => "byte", "u16" => "ushort", "u32" => "uint",
    "u64" or "usize" => "ulong", "f64" => "double", "f32" => "float", _ => null,
};

static string ToValue(string t, string v) => t switch
{
    "f64" => $"Value.FromFloat({v})", "f32" => $"Value.FromFloat32({v})", "u8" or "u16" or "u32" or "u64" or "usize" => $"Value.Num({v})", _ => $"Value.Of({v})",
};

static string FromValue(string t, string v) => t switch
{
    "f64" => $"{v}.Float", "f32" => $"{v}.Float32", "u8" or "u16" or "u32" or "u64" or "usize" => $"({Cs(t)}){v}.N", _ => $"{v}.O",
};

static string Unsigned(string t) => t switch { "u8" => "byte", "u16" => "ushort", "u32" => "uint", "u64" or "usize" => "ulong", _ => null };

static string Conv(string irTy, Type t, string v)
{
    if (irTy is "obj" or "tobj" or "tagged") return t == typeof(Obj) ? $"{v}.O" : null;
    if (Unsigned(irTy) is string u)
    {
        if (t == typeof(bool)) return $"{v}.N != 0";
        if (t.IsPrimitive && t != typeof(double) && t != typeof(float)) return $"({CsName(t)})({u}){v}.N";
        return null;
    }
    if (irTy == "f64") return t == typeof(double) ? $"{v}.Float" : null;
    if (irTy == "f32") return t == typeof(float) ? $"{v}.Float32" : null;
    return null;
}

static string Ret(string irTy, Type t, string call)
{
    if (irTy is "obj" or "tobj" or "tagged") return t == typeof(Obj) ? $"Value.Of({call})" : null;
    if (Unsigned(irTy) is string u)
    {
        if (t == typeof(bool)) return $"Value.Num({call} ? 1UL : 0UL)";
        if (t.IsPrimitive && t != typeof(double) && t != typeof(float)) return $"Value.Num(({u}){call})";
        return null;
    }
    if (irTy == "f64") return t == typeof(double) ? $"Value.FromFloat({call})" : null;
    if (irTy == "f32") return t == typeof(float) ? $"Value.FromFloat32({call})" : null;
    return null;
}

static string CsName(Type t) => t == typeof(byte) ? "byte" : t == typeof(ushort) ? "ushort" : t == typeof(uint) ? "uint"
    : t == typeof(ulong) ? "ulong" : t == typeof(sbyte) ? "sbyte" : t == typeof(short) ? "short" : t == typeof(int) ? "int"
    : t == typeof(long) ? "long" : t == typeof(nuint) ? "nuint" : "nint";
